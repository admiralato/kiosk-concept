/**
 * Generates build/version metadata from `package.json` + Git before every `start` and `build`:
 *   1. `src/app/shared/build-info.ts` — compiled into the Angular app (UI badge, console log, window global)
 *   2. `public/version.json`          — served statically at `<baseUrl>/version.json` for HTTP monitoring
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

function runGit(cmd) {
  try {
    return execSync(cmd, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
}

const pkgPath = resolve(process.cwd(), 'package.json');
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));

const envCommit =
  process.env.GIT_COMMIT ||
  process.env.GITHUB_SHA ||
  process.env.CI_COMMIT_SHA ||
  process.env.BUILD_SOURCEVERSION ||
  '';

const commitId = runGit('git rev-parse HEAD') || envCommit || 'unknown';
const shortCommitId =
  runGit('git rev-parse --short HEAD') ||
  (envCommit ? envCommit.slice(0, 7) : 'dev');
const branch =
  runGit('git rev-parse --abbrev-ref HEAD') ||
  process.env.GITHUB_REF_NAME ||
  process.env.CI_COMMIT_BRANCH ||
  'unknown';
const dirty = Boolean(runGit('git status --porcelain'));
const buildTime = new Date().toISOString();

const info = {
  appName: pkg.name || 'spaceboard-pc',
  version: pkg.version || '0.0.0',
  commitId,
  shortCommitId,
  branch,
  dirty,
  buildTime,
};

const tsContent = `// Auto-generated by scripts/generate-version.mjs — do not edit manually.

export interface BuildInfo {
  readonly appName: string;
  readonly version: string;
  readonly commitId: string;
  readonly shortCommitId: string;
  readonly branch: string;
  readonly dirty: boolean;
  readonly buildTime: string;
}

export const BUILD_INFO: BuildInfo = ${JSON.stringify(info, null, 2)} as const;
`;

writeFileSync(resolve(process.cwd(), 'src/app/shared/build-info.ts'), tsContent, 'utf8');
writeFileSync(resolve(process.cwd(), 'public/version.json'), `${JSON.stringify(info, null, 2)}\n`, 'utf8');

console.log(
  `[version] Generated build info: v${info.version} (${info.shortCommitId}${info.dirty ? '-dirty' : ''} @ ${info.branch})`,
);
